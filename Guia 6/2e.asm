VAL EQU 0
SIG EQU 4
NULL EQU -1
; IMPRIMIR_LISTA
; PUSH << PUNTERO_DOBLE >>
; CALL IMPRIMIR_LISTA
; ADD SP, 4

IMPRIMIR_LISTA:
PUSH BP
MOV BP, SP
PUSH EAX    
PUSH EBX    ; EBX : Nodo actual
PUSH ECX
PUSH EDX
PUSH EEX    ; EEX : puntero doble

MOV EEX, [BP + 8]

MOV EAX, 0X01
LDH ECX, 4
LDL ECX, 1


CICLO_IMPRIMIR:
MOV EBX, [EEX]

CMP EBX, NULL           ; llega al final de la lista
JZ FIN_IMPRIMIR

MOV EDX, EBX
ADD EDX, VAL    ; 0 en este caso
SYS 0X2

MOV EEX, EBX
ADD EEX, SIG
JMP CICLO_IMPRIMIR

FIN_IMPRIMIR:
POP EEX
POP EDX
POP ECX
POP EBX
POP EAX
MOV SP, BP
POP BP
RET